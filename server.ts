// Live Currency Exchange Rates API with caching and fallback
// -------------------------------------------------------------
interface CachedRates {
  timestamp: number;
  date: string;
  base: string;
  source: string;
  rates: Record<string, number>;
}

// Supported 18 core currencies
const SUPPORTED_CURRENCIES = [
  'USD', 'EUR', 'GBP', 'INR', 'JPY', 'CNY', 'CHF', 'CAD',
  'AUD', 'NZD', 'SGD', 'HKD', 'KRW', 'AED', 'SAR', 'BRL',
  'MXN', 'ZAR',
];

// Fallback baseline exchange rates (relative to USD = 1.0)
const FALLBACK_RATES: Record<string, number> = {
  USD: 1.0,
  EUR: 0.92,
  GBP: 0.78,
  INR: 83.45,
  JPY: 154.60,
  CNY: 7.24,
  CHF: 0.91,
  CAD: 1.37,
  AUD: 1.52,
  NZD: 1.66,
  SGD: 1.35,
  HKD: 7.82,
  KRW: 1380.50,
  AED: 3.67,
  SAR: 3.75,
  BRL: 5.15,
  MXN: 16.90,
  ZAR: 18.65,
};

let cachedRatesData: CachedRates = {
  timestamp: Date.now() - 3600000,
  date: new Date().toISOString(),
  base: 'USD',
  source: 'Fallback Baseline (Open Exchange Matrix)',
  rates: { ...FALLBACK_RATES },
};

let lastFetchAttempt = 0;
const CACHE_TTL_MS = 30 * 60 * 1000; // 30 minutes cache

async function fetchLiveExchangeRates(forceRefresh = false): Promise<CachedRates> {
  const now = Date.now();
  if (!forceRefresh && (now - lastFetchAttempt < CACHE_TTL_MS) && cachedRatesData) {
    return cachedRatesData;
  }

  lastFetchAttempt = now;

  try {
    // Open reliable public exchange rates endpoint (free tier, no auth key required)
    const res = await fetch('https://open.er-api.com/v6/latest/USD', {
      headers: { 'Accept': 'application/json' },
      signal: AbortSignal.timeout(6000),
    });

    if (res.ok) {
      const data = await res.json();
      if (data && data.rates) {
        const rates: Record<string, number> = {};
        for (const cur of SUPPORTED_CURRENCIES) {
          rates[cur] = typeof data.rates[cur] === 'number' ? data.rates[cur] : (FALLBACK_RATES[cur] || 1.0);
        }
        cachedRatesData = {
          timestamp: Date.now(),
          date: data.time_last_update_utc || new Date().toISOString(),
          base: 'USD',
          source: 'Open Exchange Rates (Live Market Midpoint)',
          rates,
        };
        return cachedRatesData;
      }
    }
  } catch (err) {
    console.warn('Live exchange rate fetch failed, serving cached fallback rates:', (err as Error).message);
  }

  return cachedRatesData;
}

// Exchange rates route
app.get('/api/exchange-rates', async (req, res) => {
  const force = req.query.force === 'true';
  const data = await fetchLiveExchangeRates(force);
  res.json({
    ...data,
    supportedCurrencies: SUPPORTED_CURRENCIES,
    isFallback: data.source.includes('Fallback'),
  });
});

